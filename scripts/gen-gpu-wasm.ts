// Writes packages/core/src/registry/rippleModule.ts from scripts/wasm/ripple-field.wat using dev-only wabt.
// Run `npm run gen:wasm` after changing the WAT source.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import wabt from 'wabt'

const watUrl = new URL('./wasm/ripple-field.wat', import.meta.url)
const outUrl = new URL(
  '../packages/core/src/registry/rippleModule.ts',
  import.meta.url,
)

export async function renderWasmModule(): Promise<string> {
  const api = await wabt()
  const src = readFileSync(watUrl, 'utf8')
  const mod = api.parseWat('ripple-field.wat', src)
  try {
    mod.validate()
    const { buffer } = mod.toBinary({
      canonicalize_lebs: true,
      write_debug_names: false,
    })
    if (buffer.length > 512)
      throw new Error(`WASM module is ${buffer.length} bytes (limit 512).`)
    const base64 = Buffer.from(buffer).toString('base64')
    if (base64.length > 684)
      throw new Error(`WASM transport is ${base64.length} bytes (limit 684).`)
    const sha256 = createHash('sha256').update(buffer).digest('hex')
    return (
      `// Generated by scripts/gen-gpu-wasm.ts. Do not edit; run \`npm run gen:wasm\`.\n` +
      `export const RIPPLE_WASM_BASE64 =\n  '${base64}'\n` +
      `export const RIPPLE_WASM_SHA256 =\n  '${sha256}'\n`
    )
  } finally {
    mod.destroy()
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(outUrl, await renderWasmModule())
}
