import { existsSync } from 'node:fs'
import { readFiles } from './check-layers.ts'
import { pathToFileURL } from 'node:url'

// Whole words, case-insensitive, except CV (capitals only). Each also matches
// an optional lower-case plural suffix (s or es) and at most one trailing digit
// (`paper2`, not `paper22`).
export const TERMS = [
  'scholar',
  'evoscholar',
  'scholaros',
  'paper',
  'publication',
  'talk',
  'CV',
  'orcid',
  'premium',
  'lab',
  'marketplace',
  'booking',
  'analytics',
]

const PATTERNS = TERMS.map(
  t =>
    [t, new RegExp(`\\b${t}(?:s|es)?\\d?\\b`, t === 'CV' ? '' : 'i')] as const,
)
const COMPOUND_SUFFIX =
  '(?:list|grid|card|row|form|page|block|item|section|box|profile|widget|view|bar|header|footer|nav|menu|link|btn|button|title|text|id)s?'
const COMPOUNDS = TERMS.filter(t => t !== 'CV').map(
  t =>
    [t, new RegExp(`\\b${t}(?:s|es)?${COMPOUND_SUFFIX}\\d?\\b`, 'i')] as const,
)

export function termHits(files: { path: string; source: string }[]): string[] {
  const out: string[] = []
  for (const { path, source } of files) {
    source.split('\n').forEach((raw, i) => {
      // split camelCase and snake_case so identifiers like paperId are seen as words
      // SRI digests are generated bytes, not identifiers or product copy.
      // Still scan the rest of the same generated line.
      const words =
        path === 'packages/core/src/scripts/scriptsMin.ts'
          ? raw.replace(/\bsha256-[A-Za-z0-9+/]{43}=(?![A-Za-z0-9+/=])/g, ' ')
          : raw
      const line = words
        // a plural acronym joined to a word (CVsList): keep the plural with the acronym
        .replace(/([A-Z]{2,}(?:s|es))(?=[A-Z])/g, '$1 ')
        .replace(/([A-Z]+)([A-Z](?!(?:s|es)\b)[a-z])/g, '$1 $2')
        .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
        .replace(/_/g, ' ')
      for (const [k, [term, re]] of PATTERNS.entries())
        if (re.test(line) || (k > 0 && COMPOUNDS[k - 1]?.[1].test(line))) {
          out.push(`${path}:${i + 1} ${term}`)
          continue
        }
    })
  }
  return out
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const roots = [
    'packages/core/src',
    'packages/tools/src',
    'packages/starter/src',
    'packages/starter/template',
  ]
  const missing = roots.find(r => !existsSync(r))
  if (missing) {
    console.error(
      `${missing} not found: run check:terms from the repository root.`,
    )
    process.exit(1)
  }
  const lines = roots.flatMap(root =>
    termHits(readFiles(root).map(f => ({ ...f, path: `${root}/${f.path}` }))),
  )
  for (const l of lines) console.log(l)
  process.exit(lines.length ? 1 : 0)
}
